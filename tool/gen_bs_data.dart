// Generates the Bikram Sambat month-length tables used by the Flutter app and
// by the native widgets / notification code from a single source of truth:
// tool/bs_month_lengths.json
//
// Run from the project root:  dart run tool/gen_bs_data.dart
import 'dart:convert';
import 'dart:io';

import 'package:patro/core/astro/bs_calculator.dart';

void main() {
  final source = jsonDecode(File('tool/bs_month_lengths.json').readAsStringSync()) as Map<String, dynamic>;
  final years = (source['years'] as Map<String, dynamic>).map(
    (k, v) => MapEntry(int.parse(k), (v as List).cast<int>()),
  );
  final sorted = years.keys.toList()..sort();
  final first = sorted.first;
  final tableLast = sorted.last;
  for (var y = first; y <= tableLast; y++) {
    final row = years[y];
    if (row == null || row.length != 12) {
      stderr.writeln('Year $y is missing or does not have 12 months');
      exit(1);
    }
  }
  final verifiedThrough = source['verifiedThrough'] as int;
  final computeThrough = source['computeThrough'] as int;

  // Extend the table astronomically, and flag projected rows the calculation
  // disagrees with so they get a second look.
  const calculator = BsCalculator();
  final epochParts = (source['epochAd'] as String).split('-').map(int.parse).toList();
  var start = DateTime.utc(epochParts[0], epochParts[1], epochParts[2]);
  for (var y = first; y <= computeThrough; y++) {
    if (y > verifiedThrough) {
      final computed = calculator.year(start).lengths;
      if (y > tableLast) {
        years[y] = computed;
      } else if (computed.toString() != years[y].toString()) {
        stdout.writeln('Note: projected $y differs from the calculation $computed');
      }
    }
    start = start.add(Duration(days: years[y]!.fold<int>(0, (a, b) => a + b)));
  }
  sorted
    ..clear()
    ..addAll(years.keys.toList()..sort());
  final last = sorted.last;
  const header =
      'GENERATED by tool/gen_bs_data.dart from tool/bs_month_lengths.json. '
      'Do not edit by hand.';

  String rows(String open, String close, String sep) =>
      [for (final y in sorted) '    $open${years[y]!.join(', ')}$close$sep // $y'].join('\n');

  File('lib/core/bs/bs_data.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync('''
// $header

/// First BS year covered by [bsMonthLengths].
const int bsFirstYear = $first;

/// Last BS year covered by [bsMonthLengths].
const int bsLastYear = $last;

/// Years up to this one are checked against published calendars; later ones
/// are projections or astronomical calculations and are shown as estimates.
const int bsVerifiedThroughYear = $verifiedThrough;

/// AD date of 1 Baisakh [bsFirstYear].
final DateTime bsEpochAd = DateTime.utc(${epochParts[0]}, ${epochParts[1]}, ${epochParts[2]});

/// Days in each month (Baisakh..Chaitra) for every year from [bsFirstYear].
const List<List<int>> bsMonthLengths = [
${rows('[', ']', ',')}
];
''');

  final kotlinDir = Directory('android/app/src/main/kotlin/com/nepali/patro/bs')..createSync(recursive: true);
  File('${kotlinDir.path}/BsData.kt').writeAsStringSync('''
// $header
package com.nepali.patro.bs

object BsData {
    const val FIRST_YEAR = $first
    const val LAST_YEAR = $last
    const val VERIFIED_THROUGH_YEAR = $verifiedThrough
    const val EPOCH_AD_YEAR = ${epochParts[0]}
    const val EPOCH_AD_MONTH = ${epochParts[1]}
    const val EPOCH_AD_DAY = ${epochParts[2]}

    @JvmField
    val MONTH_LENGTHS: Array<IntArray> = arrayOf(
${rows('intArrayOf(', ')', ',')}
    )
}
''');

  final swiftDir = Directory('ios/PatroWidget')..createSync(recursive: true);
  File('${swiftDir.path}/BsData.swift').writeAsStringSync('''
// $header
import Foundation

enum BsData {
    static let firstYear = $first
    static let lastYear = $last
    static let verifiedThroughYear = $verifiedThrough
    static let epochAd = DateComponents(year: ${epochParts[0]}, month: ${epochParts[1]}, day: ${epochParts[2]})

    static let monthLengths: [[Int]] = [
${rows('[', ']', ',')}
    ]
}
''');

  stdout.writeln('Generated BS tables for $first-$last (table to $tableLast, verified to $verifiedThrough)');
}
